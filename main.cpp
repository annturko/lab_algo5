// ЗАВДАННЯ 2 (Варіант 6)
// Обчислити суму: sum_{i=1}^n ( ln(x^(i-1)) / ((-1)^i / x) ), 0.5 <= x <= 2.
// Варіант 6 парний -> вивести значення кожного третього елемента.
// ============================================================================
void task2() {
    cout << "\n--- Завдання 2 (Варіант 6) ---\n";

    double x = inputDouble("Введіть дійсне число x (0.5 <= x <= 2): ", 0.5, 2.0);
    int n = inputInt("Введіть натуральне число n (n >= 1): ", 1);

    double sum = 0.0;
    double lnX = log(x); // Обчислюємо ln(x) один раз перед циклом для оптимізації
    int sign = -1;       // Значення (-1)^i при i = 1

    cout << fixed << setprecision(6);
    cout << "Значення кожного третього елемента:\n";

    for (int i = 1; i <= n; i++) {
        // Спрощений вигляд i-го члена: (i - 1) * ln(x) * (-1)^i * x
        double term = sign * x * (i - 1) * lnX;
        sum += term;

        // Виведення кожного 3-го елемента (для парних варіантів)
        if (i % 3 == 0) {
            cout << "  Елемент #" << i << " = " << term << endl;
        }

        sign = -sign; // Зміна знаку для наступної ітерації
    }

    if (n < 3) {
        cout << "  (Елементів з номером, кратним 3, немає, оскільки n < 3)\n";
    }

    cout << "Сума виразу S = " << sum << endl;
}

// ============================================================================
// ЗАВДАННЯ 3 (Варіант 9)
// Дослідити на збіжність ряд: sum_{n=1}^infty ((n^2 + 5) / 2^n).
// ============================================================================
void task3() {
    cout << "\n--- Завдання 3 (Варіант 9) ---\n";

    double e = inputDouble("Введіть малу величину e (1e-20 <= e <= 1e-1): ", 1e-20, 1e-1);
    double g = inputDouble("Введіть велику величину g (10 <= g <= 1e6): ", 10.0, 1e6);
    int stepM = inputInt("Введіть крок виведення M (M >= 1): ", 1);

    int n = 1;
    double denom = 2.0;               // Знаменник 2^n при n = 1
    double u = (n * n + 5.0) / denom; // Перший член ряду u_1
    double sum = 0.0;

    // Виведення наростаючої суми з фіксованою позицією точки та 15 знаками після коми
    cout << fixed << setprecision(15);

    // Цикл із передумовою триває, поки |u_n| >= e та |u_n| <= g
    while (fabs(u) >= e && fabs(u) <= g) {
        sum += u;

        // Виведення проміжних результатів із кроком M
        if (n % stepM == 0) {
            cout << "n = " << setw(3) << n << " | u_n = " << u << " | sum = " << sum << endl;
        }

        // Обчислення наступного члена ряду
        n++;
        denom *= 2.0;
        u = (n * n + 5.0) / denom;
    }

    cout << "\nОбчислення зупинено на кроці n = " << n << endl;
    if (fabs(u) < e) {
        cout << "Висновок: ряд ЗБІЖНИЙ (|u_n| < e)." << endl;
    } else {
        cout << "Висновок: ряд РОЗБІЖНИЙ (|u_n| > g)." << endl;
    }
    cout << "Накопичена сума ряду: " << sum << endl;
}
