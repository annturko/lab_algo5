// ЗАВДАННЯ 1 (Варіант 36 — оливкова область)
// Визначити кількість точок (x_i, y_i), що потрапляють у задану фігуру.
// ============================================================================
void task1() {
    cout << "\n--- Завдання 1 (Варіант 36) ---\n";

    double r = inputDouble("Введіть радіус кола r (r > 0): ", 1e-9);
    int n = inputInt("Введіть кількість точок n (n >= 1): ", 1);

    const double EPS = 1e-9;   // Похибка для порівняння дійсних чисел на межах
    double c = r / sqrt(2.0);  // Координати центра кола (c; c)
    double a = r * sqrt(2.0);  // Півдіагональ ромба (2c)
    int count = 0;             // Лічильник точок, що потрапили у фігуру

    // Параметризований цикл для перевірки кожної з n точок
    for (int i = 1; i <= n; i++) {
        cout << "Точка #" << i << ":\n";
        double x = inputDouble("  x = ");
        double y = inputDouble("  y = ");

        // Умова належності колу: (x - c)^2 + (y - c)^2 <= r^2
        bool inCircle = ((x - c) * (x - c) + (y - c) * (y - c)) <= (r * r + EPS);
        // Умова належності ромбу: |x| + |y| <= r * sqrt(2)
        bool inRhombus = (fabs(x) + fabs(y)) <= (a + EPS);

        // Верхня частина фігури (I чверть: всередині ромба, вище прямої y = x)
        bool part1 = (x >= -EPS) && (y >= -EPS) && inRhombus && (y >= x - EPS);
        // Нижня частина фігури (IV чверть: сегмент кола нижче осі OX)
        bool part2 = (x >= -EPS) && (y <= EPS) && inCircle;

        if (part1 || part2) {
            count++;
            cout << "  -> Точка ПОТРАПЛЯЄ у фігуру.\n";
        } else {
            cout << "  -> Точка НЕ потрапляє у фігуру.\n";
        }
    }

    cout << "Кількість точок, що потрапили у фігуру: " << count << endl;
}

